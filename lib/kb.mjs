// The knowledge graph: practices in kb/practices, tools in kb/tools, learnings in learnings/,
// linked by the edges in their frontmatter. Everything under kb/ except practices/, tools/ and
// _vocab.json, and the topic files of the best-practices skill, is generated from them by
// scripts/build-kb.mjs.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseFrontmatter } from "./frontmatter.mjs";

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const SKILL_DIR = "plugins/agent-workflow/skills/best-practices";
const TOPICS_BEGIN = "<!-- kb:topics:begin -->";
const TOPICS_END = "<!-- kb:topics:end -->";
const GENERATED = "<!-- Generated by scripts/build-kb.mjs from kb/practices. Edit the nodes, not this file. -->";
const STATUSES = ["active", "stale", "retired"];
const SEVERITY_RANK = { must: 0, should: 1, tip: 2 };
const EDGES = ["derived_from", "implemented_by", "related", "supersedes"];
const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const LEARNING_ID = /^\d{4}-\d{2}-\d{2}-[a-z0-9]+(-[a-z0-9]+)*$/;

export const tokens = (text) => Math.ceil(text.length / 4);

// Token budgets (characters / 4). Over budget means merge or retire something, not raise the number.
export const BUDGET = {
  alwaysOn: 1100,     // T0: name + description of every skill and agent, loaded in every session
  mustRules: 600,     // T0: what the SessionStart hook prints in a project
  practiceCard: 150,  // T2: one node file
  bundle: 2000,       // T1: one stack bundle
  index: 1500,        // T1: kb/INDEX.md
  skillBody: 1500,    // T1: a SKILL.md body, except the T3 skills
};
const list = (v) => (Array.isArray(v) ? v : v === undefined ? [] : [v]);

function readDir(dir, ext = ".md") {
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(ext)).sort() : [];
}

export function loadKb(root = ROOT) {
  const vocab = JSON.parse(fs.readFileSync(path.join(root, "kb/_vocab.json"), "utf8"));
  const practices = readDir(path.join(root, "kb/practices")).map((file) => {
    const raw = fs.readFileSync(path.join(root, "kb/practices", file), "utf8");
    const fm = parseFrontmatter(raw);
    return { file, raw, parsed: !!fm, ...(fm?.data ?? {}), body: (fm?.body ?? "").trim(), tokens: tokens(raw) };
  });
  const learnings = readDir(path.join(root, "learnings"))
    .filter((f) => f !== "README.md")
    .map((file) => {
      const raw = fs.readFileSync(path.join(root, "learnings", file), "utf8");
      const fm = parseFrontmatter(raw);
      const title = (fm?.body ?? "").match(/^#\s+(.+)$/m)?.[1].trim() ?? "";
      return { file, raw, id: file.replace(/\.md$/, ""), type: "learning", title, ...(fm?.data ?? {}), tokens: tokens(raw) };
    });
  const tools = readDir(path.join(root, "kb/tools")).map((file) => {
    const raw = fs.readFileSync(path.join(root, "kb/tools", file), "utf8");
    const fm = parseFrontmatter(raw);
    return { file, raw, parsed: !!fm, ...(fm?.data ?? {}), tokens: tokens(raw) };
  });
  return { root, vocab, practices, tools, learnings };
}

// Returns a list of problems. Empty means the graph is sound.
export function validate({ root, vocab, practices, tools = [], learnings }) {
  const errors = [];
  const err = (who, msg) => errors.push(`${who}: ${msg}`);
  const learningIds = new Set(learnings.map((l) => l.id));
  const practiceIds = new Set(practices.map((p) => p.id));
  const seen = new Set();
  const day = /^\d{4}-\d{2}-\d{2}$/;

  for (const t of tools) {
    const who = `kb/tools/${t.file}`;
    if (!t.parsed) { err(who, "no frontmatter"); continue; }
    if (t.id !== t.file.replace(/\.md$/, "")) err(who, `id "${t.id}" must equal the file name`);
    if (!ID.test(t.id ?? "")) err(who, "id must be lowercase words joined by hyphens");
    if (seen.has(t.id)) err(who, "duplicate id");
    seen.add(t.id);
    if (t.type !== "tool") err(who, "type must be tool");
    if (!vocab.toolKinds.includes(t.kind)) err(who, `kind must be one of ${vocab.toolKinds.join(", ")}`);
    if (!vocab.toolStates.includes(t.state)) err(who, `state must be one of ${vocab.toolStates.join(", ")}`);
    if (!t.summary) err(who, "missing summary");
    else if (t.summary.length > 140) err(who, `summary is ${t.summary.length} chars, max 140`);
    if (!t.use_when) err(who, "missing use_when");
    else if (t.use_when.length > 200) err(who, `use_when is ${t.use_when.length} chars, max 200`);
    if (!day.test(t.last_reviewed ?? "")) err(who, "last_reviewed must be YYYY-MM-DD");
    if (!t.where) err(who, "missing where");
    else if (t.kind === "plugin" || t.kind === "mcp") {
      if (!/^[a-z0-9][a-z0-9-]*@[a-z0-9][a-z0-9-]*$/.test(t.where)) err(who, "where must be name@marketplace");
    } else if (!fs.existsSync(path.join(root, t.where))) err(who, `where ${t.where} does not exist`);
    if ([t.summary, t.use_when].some((x) => x?.includes("\u2014"))) err(who, "has an em dash");
  }

  for (const p of practices) {
    const who = `kb/practices/${p.file}`;
    if (!p.parsed) { err(who, "no frontmatter"); continue; }
    if (p.id !== p.file.replace(/\.md$/, "")) err(who, `id "${p.id}" must equal the file name`);
    if (!ID.test(p.id ?? "")) err(who, "id must be lowercase words joined by hyphens");
    if (seen.has(p.id)) err(who, "duplicate id");
    seen.add(p.id);
    if (p.type !== "practice") err(who, "type must be practice");
    if (!p.summary) err(who, "missing summary");
    else if (p.summary.length > 140) err(who, `summary is ${p.summary.length} chars, max 140`);
    if (!vocab.concerns[p.concern]) err(who, `concern "${p.concern}" is not in kb/_vocab.json`);
    if (!list(p.stack).length) err(who, "stack is empty, use [any]");
    for (const s of list(p.stack)) if (!vocab.stacks.includes(s)) err(who, `stack "${s}" is not in kb/_vocab.json`);
    if (!vocab.severities.includes(p.severity)) err(who, `severity must be one of ${vocab.severities.join(", ")}`);
    if (!STATUSES.includes(p.status)) err(who, `status must be one of ${STATUSES.join(", ")}`);
    if (!day.test(p.last_verified ?? "")) err(who, "last_verified must be YYYY-MM-DD");
    const derived = list(p.derived_from);
    if (derived.length) {
      if (p.source) err(who, "has derived_from, so drop source");
    } else {
      if (p.source !== "judgment") err(who, "no derived_from: cite a learning, or set source: judgment");
      if (p.severity === "must") err(who, "a judgment call cannot be severity must");
    }
    for (const id of derived) if (!learningIds.has(id)) err(who, `derived_from ${id} is not in learnings/`);
    for (const target of list(p.implemented_by)) {
      if (!fs.existsSync(path.join(root, target))) err(who, `implemented_by ${target} does not exist`);
    }
    for (const edge of ["related", "supersedes"]) {
      for (const id of list(p[edge])) {
        if (id === p.id) err(who, `${edge} points at itself`);
        else if (!practiceIds.has(id)) err(who, `${edge} ${id} is not a practice`);
      }
    }
    if (p.body.includes("\u2014") || p.summary?.includes("\u2014")) err(who, "has an em dash");
  }

  const derivedAll = new Set(practices.flatMap((p) => list(p.derived_from)));
  for (const l of learnings) {
    if (!LEARNING_ID.test(l.id)) err(`learnings/${l.file}`, "name it YYYY-MM-DD-slug.md");
    if (l.raw?.includes("TODO")) err(`learnings/${l.file}`, "still has TODO from the template: write the learning");
    const toPractice = list(l.promoted_to).some((t) => t.includes("skills/best-practices/"));
    if (toPractice && !derivedAll.has(l.id)) {
      err(`learnings/${l.file}`, "says it is a practice, but no kb/practices node derives from it");
    }
  }
  return errors;
}

const bySeverity = (a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || a.id.localeCompare(b.id);
const active = (practices) => practices.filter((p) => p.status === "active");

function wrap(text, indent = "", width = 92) {
  const lines = [];
  let cur = "";
  for (const word of text.split(/\s+/).filter(Boolean)) {
    if (cur && (indent + cur + " " + word).length > width) { lines.push(cur); cur = word; }
    else cur = cur ? cur + " " + word : word;
  }
  if (cur) lines.push(cur);
  return lines.map((l, i) => (i ? indent : "") + l).join("\n");
}

function topicFile(concern, meta, practices) {
  const bullets = practices.filter((p) => p.concern === concern && p.status === "active").sort(bySeverity).map((p) => {
    const cites = list(p.derived_from).map((id) => `*(${id})*`).join(" ");
    return wrap(`- **${p.summary}** ${p.body.replace(/\s+/g, " ")}${cites ? " " + cites : ""}`, "  ");
  });
  return `${GENERATED}\n# ${meta.title}\n\n${bullets.join("\n")}\n`;
}

function topicTable(vocab) {
  const rows = Object.values(vocab.concerns).map((c) => `| [${c.file}](${c.file}) | ${c.readBefore} |`);
  return `${TOPICS_BEGIN}\n| Topic | Read it before |\n| --- | --- |\n${rows.join("\n")}\n${TOPICS_END}`;
}

export function stackBundles(vocab, practices) {
  const act = active(practices);
  const stacks = vocab.stacks.filter((s) => s === "any" || act.some((p) => list(p.stack).includes(s)));
  return stacks.map((stack) => ({
    stack,
    practices: act.filter((p) => list(p.stack).includes("any") || list(p.stack).includes(stack)),
  }));
}

function bundle(title, items, vocab, where) {
  const out = [
    GENERATED,
    `# Practices for stack: ${title}`,
    "",
    `One line per practice, \`must\` first. The card with the reason is \`${where.cards}/<id>.md\`.`,
    `Search every node: \`grep -i <term> ${where.index}\`.`,
  ];
  for (const [concern, meta] of Object.entries(vocab.concerns)) {
    const rows = items.filter((p) => p.concern === concern).sort(bySeverity);
    if (!rows.length) continue;
    out.push("", `## ${meta.title}`);
    for (const p of rows) out.push(`- [${p.severity}] ${p.id}: ${p.summary}`);
  }
  return out.join("\n") + "\n";
}

function indexMd({ vocab, practices, tools = [], learnings }) {
  const act = active(practices);
  const rows = Object.entries(vocab.concerns).map(([c, m]) => {
    const n = act.filter((p) => p.concern === c).length;
    return `| ${m.title} | ${n} | ${m.readBefore} |`;
  });
  const must = act.filter((p) => p.severity === "must").sort(bySeverity);
  return [
    GENERATED,
    "# Knowledge index",
    "",
    `${act.length} active practices, ${learnings.length} learnings. Load the least that answers the question:`,
    "",
    "1. `kb/bundles/<stack>.md`: one line per practice for a stack (`any` always applies).",
    "2. `grep -i <term> kb/index.jsonl`: one JSON line per node, with edges.",
    "3. `kb/practices/<id>.md`: the card, with the reason. Its `derived_from` names the evidence.",
    "",
    "| Concern | Practices | Read before |",
    "| --- | --- | --- |",
    ...rows,
    "",
    "## Must rules",
    ...must.map((p) => `- ${p.id}: ${p.summary}`),
    "",
    "## Tools",
    ...tools.filter((t) => t.state === "installed").map((t) => `- ${t.id} (${t.kind}): ${t.summary}`),
    "",
  ].join("\n");
}

export function indexLines({ practices, tools = [], learnings }) {
  const lines = [];
  for (const p of [...practices].sort((a, b) => a.concern.localeCompare(b.concern) || bySeverity(a, b))) {
    lines.push({
      id: p.id, type: "practice", summary: p.summary, concern: p.concern, stack: list(p.stack),
      severity: p.severity, status: p.status, seen: list(p.derived_from).length, tokens: p.tokens,
      last_verified: p.last_verified, derived_from: list(p.derived_from),
      implemented_by: list(p.implemented_by), related: list(p.related), supersedes: list(p.supersedes),
    });
  }
  for (const t of tools) {
    lines.push({
      id: t.id, type: "tool", kind: t.kind, summary: t.summary, use_when: t.use_when,
      where: t.where, state: t.state, tokens: t.tokens, last_reviewed: t.last_reviewed,
    });
  }
  for (const l of learnings) {
    lines.push({
      id: l.id, type: "learning", summary: l.title, tags: list(l.tags), status: l.status,
      source: l.source, tokens: l.tokens, promoted_to: list(l.promoted_to),
    });
  }
  return lines;
}

export function graph(kb) {
  const nodes = indexLines(kb);
  const edges = [];
  for (const n of nodes) {
    if (n.type === "practice") {
      edges.push({ from: n.id, to: n.concern, type: "concern" });
      for (const s of n.stack) edges.push({ from: n.id, to: s, type: "stack" });
      for (const e of EDGES) for (const to of n[e]) edges.push({ from: n.id, to, type: e });
    } else if (n.type === "learning") {
      for (const to of n.promoted_to) edges.push({ from: n.id, to, type: "promoted_to" });
    }
  }
  return { nodes, edges };
}

// Every generated file, as relPath -> content.
export function render(kb) {
  const { root, vocab, practices } = kb;
  const files = new Map();
  for (const [concern, meta] of Object.entries(vocab.concerns)) {
    files.set(`${SKILL_DIR}/${meta.file}`, topicFile(concern, meta, practices));
  }
  const skill = fs.readFileSync(path.join(root, SKILL_DIR, "SKILL.md"), "utf8");
  const begin = skill.indexOf(TOPICS_BEGIN);
  const end = skill.indexOf(TOPICS_END);
  if (begin < 0 || end < begin) throw new Error(`${SKILL_DIR}/SKILL.md needs ${TOPICS_BEGIN} and ${TOPICS_END}`);
  files.set(`${SKILL_DIR}/SKILL.md`, skill.slice(0, begin) + topicTable(vocab) + skill.slice(end + TOPICS_END.length));

  files.set("kb/index.jsonl", indexLines(kb).map((l) => JSON.stringify(l)).join("\n") + "\n");
  files.set("kb/graph.json", JSON.stringify(graph(kb), null, 2) + "\n");
  files.set("kb/INDEX.md", indexMd(kb));
  const hub = { cards: "kb/practices", index: "kb/index.jsonl" };
  for (const b of stackBundles(vocab, practices)) files.set(`kb/bundles/${b.stack}.md`, bundle(b.stack, b.practices, vocab, hub));
  return files;
}

// What a project repo gets for the stacks it declared: relPath (under .claude/knowledge/) -> content.
// `any` always applies. Learnings are not included, they are never synced.
export function knowledgeFor(kb, stacks = []) {
  const { vocab, practices } = kb;
  for (const s of stacks) if (!vocab.stacks.includes(s)) throw new Error(`unknown stack "${s}", known: ${vocab.stacks.join(", ")}`);
  const want = new Set(["any", ...stacks]);
  const items = active(practices).filter((p) => list(p.stack).some((s) => want.has(s)));
  const label = ["any", ...stacks.filter((s) => s !== "any")].join(", ");
  const files = new Map();
  files.set("bundle.md", bundle(label, items, vocab, { cards: ".claude/knowledge/practices", index: ".claude/knowledge/index.jsonl" }));
  const must = items.filter((p) => p.severity === "must").sort(bySeverity);
  files.set("must.md", [
    "Must rules from claude-code-setup. One line each; the rest is in .claude/knowledge/bundle.md,",
    "and each card in .claude/knowledge/practices/<id>.md says why.",
    ...must.map((p) => `- ${p.id}: ${p.summary}`),
    "",
  ].join("\n"));
  for (const p of items) files.set(`practices/${p.id}.md`, p.raw);
  const keep = new Set(items.map((p) => p.id));
  const lines = indexLines({ practices: items, tools: kb.tools ?? [], learnings: [] }).filter((l) => l.type !== "practice" || keep.has(l.id));
  files.set("index.jsonl", lines.map((l) => JSON.stringify(l)).join("\n") + "\n");
  return files;
}
